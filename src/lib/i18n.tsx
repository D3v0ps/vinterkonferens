const dicts: Record<Lang, Dict> = { sv, en, ar }

interface I18n {
  lang: Lang
  t: Dict
  dir: 'ltr' | 'rtl'
  setLang: (l: Lang) => void
  /** true om besökaren själv valt språk (annars styr dagens standardspråk). */
  chosen: boolean
}

const Ctx = createContext<I18n | null>(null)
const KEY = 'vk-lang'

export function I18nProvider({ children, fallback }: { children: ReactNode; fallback: Lang }) {
  const [chosenLang, setChosen] = useState<Lang | null>(() => {
    const v = safeStorage.get(KEY)
    return v === 'sv' || v === 'en' || v === 'ar' ? v : null
  })
  const lang = chosenLang ?? fallback
  const dir = lang === 'ar' ? 'rtl' : 'ltr'

  useEffect(() => {
    document.documentElement.lang = lang
    document.documentElement.dir = dir
    return () => {
      document.documentElement.lang = 'sv'
      document.documentElement.dir = 'ltr'
    }
  }, [lang, dir])

  const value = useMemo<I18n>(
    () => ({
      lang,
      t: dicts[lang],
      dir,
      chosen: !!chosenLang,
      setLang: (l) => {
        setChosen(l)
        safeStorage.set(KEY, l)
      },
    }),
    [lang, dir, chosenLang],
  )
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n(): I18n {
  const v = useContext(Ctx)
  if (!v) throw new Error('useI18n utanför I18nProvider')
  return v
}

